#!/usr/bin/env python3
"""prune_task_node_modules.py -- deterministic cleanup for per-task-node
node_modules trees under /opt/veridian/ai-os/tasks/*/workspace/node_modules.

Root cause this fixes (real Owner-dispatched disk investigation chain,
UMR-20260806-071025-1d28 -> UMR-20260806-082230-54b8): every worker
workspace `npm install`/`bun install`s its own per-task
workspace/node_modules, and until this script existed nothing ever pruned
it back out once that task was done. Left unpruned across O(1000) task
directories this is the single largest reclaimable chunk of disk under
/opt/veridian/ai-os/tasks -- fully regenerable from bun.lock/package.json
by a future `bun install`, so pruning it destroys no real work.

Honest note on the number that originally motivated this (515 node_modules
dirs / 288G): re-measured live at authorship time (2026-08-06, ~19:50Z+)
there were only 17 such directories total on the whole box, and every one
of them belonged to a task in a non-terminal `blocked` status -- i.e. zero
were actually eligible for deletion under the policy below, because that
policy already existed as a rule (just not as running code) before this
script did. The 515/288G figure was stale queued-dispatch prompt text
replayed hours after the real state had already changed -- see this
script's sibling investigation UMR-20260806-151638-48cc (real root cause
of the replay itself: resource_governor.py's next_queued_task() dispatching
rows flag_stale_queued_tasks() had already marked STALE-QUEUED, fixed in
veridian-scripts PR #184). This script is what actually keeps the number at
zero going forward -- see prune_one()'s call site in veridian-task.py
cmd_checkpoint, which self-prunes a task's own node_modules the instant
that task's own checkpoint lands a terminal status, so this can never
silently reaccumulate the way it did before this existed.

POLICY (matches the real Owner-authorized safety rule verbatim, per
UMR-20260806-082230-54b8):
  - Only ever deletes workspace/node_modules under a task directory whose
    own task.yaml `status:` field is one of TERMINAL_STATES below.
  - Never touches task.yaml itself, any log file, .task.lock,
    superboss-register.sqlite, /opt/veridian/backups, or any repo under
    /opt/veridian/repos -- this script only ever removes a single
    `workspace/node_modules` directory tree per task, nothing else.
  - PROTECTED_TASK_IDS are always skipped regardless of task.yaml status --
    belt-and-suspenders should either of them ever be miscategorized as
    terminal (a genuinely-running build's task.yaml is never itself in
    TERMINAL_STATES, so in practice this is redundant with the status gate,
    not a substitute for it).

TWO CALL SHAPES:
  1. Standalone sweep (this file's __main__ / a daily systemd timer):
     scans every task dir under --tasks-root, applies the terminal-state
     gate to each.
  2. Library import -- wired into veridian-task.py's `checkpoint --status`
     command, the single real place a task's own status transitions to a
     terminal value: `prune_task_node_modules.prune_one(task_dir, status)`
     self-prunes just that one task's own node_modules the moment ITS
     checkpoint call lands a terminal status. This is the actual
     recurrence fix -- it does not depend on the daily sweep ever running.

Usage:
    prune_task_node_modules.py --dry-run
    prune_task_node_modules.py
    prune_task_node_modules.py --tasks-root DIR

Exit codes: 0 success (dry-run or real), 2 bad arguments.
"""
import argparse
import json
import os
import shutil
import sys
from datetime import datetime, timezone

TASKS_ROOT_DEFAULT = "/opt/veridian/ai-os/tasks"

TERMINAL_STATES = {"completed", "failed", "killed", "superseded", "rejected_duplicate"}

# Real legitimately-running builds cited by the Owner at authorship time
# (UMR-20260806-082230-54b8). This is deliberate belt-and-suspenders, not
# the primary control: the TERMINAL_STATES gate below already excludes any
# task that is still genuinely running (its task.yaml status can't be
# terminal while that's true), so in the normal case this set is inert.
# It only matters if a task's own status is ever wrongly marked terminal
# while real work is still in flight -- see the module docstring's honest
# note above for the real state as of authorship.
PROTECTED_TASK_IDS = {
    "task-20260806-075810-merge-pr-959-compliance-tracker--real-au",
    "task-20260806-072103-adopted-reconcile-umr-20260805-130947-f0a7--merg",
}


def _read_status(task_yaml_path):
    """Real minimal status-field reader -- avoids a yaml dependency here and
    avoids parsing/re-serializing the whole task.yaml (which could race a
    concurrent writer holding .task.lock); reads the raw `status: <value>`
    line only, the same shape veridian-task.py's own save_task() writes via
    yaml.safe_dump(sort_keys=False) with `status` as a top-level scalar."""
    try:
        with open(task_yaml_path, errors="replace") as f:
            for line in f:
                if line.startswith("status:"):
                    return line.split(":", 1)[1].strip()
    except OSError:
        return None
    return None


def dir_size(path):
    total = 0
    for root, _dirs, files in os.walk(path):
        for fn in files:
            fp = os.path.join(root, fn)
            try:
                total += os.path.getsize(fp)
            except OSError:
                pass
    return total


def prune_one(task_dir, status=None, dry_run=False):
    """Prunes workspace/node_modules under a single task_dir if eligible.
    Returns a report dict; never raises for the normal "not eligible" or
    "nothing to delete" cases -- a real filesystem error during the delete
    itself is reported in the dict, not raised, so a caller wired into a
    checkpoint's hot path (see veridian-task.py cmd_checkpoint) can treat
    this as fully best-effort."""
    task_id = os.path.basename(task_dir.rstrip("/"))
    nm_path = os.path.join(task_dir, "workspace", "node_modules")
    if status is None:
        status = _read_status(os.path.join(task_dir, "task.yaml"))
    entry = {"task_id": task_id, "status": status, "node_modules": nm_path}

    if task_id in PROTECTED_TASK_IDS:
        entry["action"] = "skipped-protected"
        return entry
    if status not in TERMINAL_STATES:
        entry["action"] = "skipped-not-terminal"
        return entry
    if not os.path.isdir(nm_path):
        entry["action"] = "skipped-no-node-modules"
        return entry

    entry["bytes"] = dir_size(nm_path)
    if dry_run:
        entry["action"] = "would-delete"
        return entry
    try:
        shutil.rmtree(nm_path)
        entry["action"] = "deleted"
    except OSError as e:
        entry["action"] = "error"
        entry["error"] = str(e)
    return entry


def run(tasks_root, dry_run):
    results = []
    if os.path.isdir(tasks_root):
        for task_id in sorted(os.listdir(tasks_root)):
            task_dir = os.path.join(tasks_root, task_id)
            if not os.path.isdir(task_dir):
                continue
            if not os.path.isfile(os.path.join(task_dir, "task.yaml")):
                continue
            entry = prune_one(task_dir, dry_run=dry_run)
            if entry["action"] in ("deleted", "would-delete", "error"):
                results.append(entry)
    reclaimed = sum(e.get("bytes", 0) for e in results if e["action"] in ("deleted", "would-delete"))
    return {
        "mode": "dry-run" if dry_run else "real-delete",
        "tasks_root": tasks_root,
        "protected_task_ids": sorted(PROTECTED_TASK_IDS),
        "terminal_states": sorted(TERMINAL_STATES),
        "touched": results,
        "reclaimed_bytes": reclaimed,
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="Prune workspace/node_modules under task directories whose "
                     "own task.yaml status has reached a terminal state.")
    ap.add_argument("--dry-run", action="store_true",
                     help="Print exactly what would be deleted; delete nothing.")
    ap.add_argument("--tasks-root", default=TASKS_ROOT_DEFAULT,
                     help=f"Root directory to scan (default {TASKS_ROOT_DEFAULT}).")
    args = ap.parse_args(argv)
    report = run(args.tasks_root, args.dry_run)
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
