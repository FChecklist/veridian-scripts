#!/usr/bin/env python3
"""Real tests for prune_task_node_modules.py (child of real disk-emergency
investigation UMR-20260806-082230-54b8, parent UMR-20260806-071025-1d28).

Every test builds a real tempdir tree shaped like /opt/veridian/ai-os/tasks
(task_dir/task.yaml + task_dir/workspace/node_modules/<real files>) and
drives the module's real functions (prune_one()/run()/main()) against it --
no mocking of the filesystem. Imports the module via the same
importlib-by-file-path pattern used elsewhere in this repo.
"""
import importlib.util
import json
import os
import subprocess
import sys
import tempfile

SCRIPTS_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _load_module():
    spec = importlib.util.spec_from_file_location(
        "prune_task_node_modules_test", os.path.join(SCRIPTS_DIR, "prune_task_node_modules.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _make_task(root, task_id, status, with_node_modules=True, nm_file_bytes=b"x" * 1024):
    task_dir = os.path.join(root, task_id)
    ws = os.path.join(task_dir, "workspace")
    os.makedirs(ws)
    with open(os.path.join(task_dir, "task.yaml"), "w") as f:
        f.write(f"id: {task_id}\nstatus: {status}\ntitle: real test task\n")
    if with_node_modules:
        nm = os.path.join(ws, "node_modules", "some-pkg")
        os.makedirs(nm)
        with open(os.path.join(nm, "index.js"), "wb") as f:
            f.write(nm_file_bytes)
    return task_dir


def test_terminal_state_with_node_modules_is_deleted():
    m = _load_module()
    with tempfile.TemporaryDirectory() as root:
        task_dir = _make_task(root, "task-a", "completed")
        entry = m.prune_one(task_dir)
        assert entry["action"] == "deleted"
        assert entry["bytes"] == 1024
        assert not os.path.isdir(os.path.join(task_dir, "workspace", "node_modules"))
        assert os.path.isfile(os.path.join(task_dir, "task.yaml")), "task.yaml must never be touched"


def test_all_five_terminal_states_are_eligible():
    m = _load_module()
    for status in ("completed", "failed", "killed", "superseded", "rejected_duplicate"):
        with tempfile.TemporaryDirectory() as root:
            task_dir = _make_task(root, f"task-{status}", status)
            entry = m.prune_one(task_dir)
            assert entry["action"] == "deleted", f"status={status} should be eligible"


def test_non_terminal_status_is_never_touched():
    m = _load_module()
    for status in ("blocked", "in_progress", "pending_review", "awaiting_human_approval",
                   "cancelled", "not_needed", "queued"):
        with tempfile.TemporaryDirectory() as root:
            task_dir = _make_task(root, f"task-{status}", status)
            entry = m.prune_one(task_dir)
            assert entry["action"] == "skipped-not-terminal", f"status={status} must not be pruned"
            assert os.path.isdir(os.path.join(task_dir, "workspace", "node_modules"))


def test_protected_task_id_never_deleted_even_if_status_is_terminal():
    m = _load_module()
    with tempfile.TemporaryDirectory() as root:
        protected_id = sorted(m.PROTECTED_TASK_IDS)[0]
        task_dir = _make_task(root, protected_id, "completed")
        entry = m.prune_one(task_dir)
        assert entry["action"] == "skipped-protected"
        assert os.path.isdir(os.path.join(task_dir, "workspace", "node_modules"))


def test_terminal_status_but_no_node_modules_is_a_noop():
    m = _load_module()
    with tempfile.TemporaryDirectory() as root:
        task_dir = _make_task(root, "task-none", "completed", with_node_modules=False)
        entry = m.prune_one(task_dir)
        assert entry["action"] == "skipped-no-node-modules"


def test_dry_run_reports_but_deletes_nothing():
    m = _load_module()
    with tempfile.TemporaryDirectory() as root:
        task_dir = _make_task(root, "task-dry", "failed")
        entry = m.prune_one(task_dir, dry_run=True)
        assert entry["action"] == "would-delete"
        assert entry["bytes"] == 1024
        assert os.path.isdir(os.path.join(task_dir, "workspace", "node_modules"))


def test_run_sweeps_a_whole_tasks_root_correctly():
    m = _load_module()
    with tempfile.TemporaryDirectory() as root:
        _make_task(root, "task-1-completed", "completed")
        _make_task(root, "task-2-blocked", "blocked")
        _make_task(root, "task-3-failed", "failed")
        _make_task(root, "task-4-no-yaml-dir-only", "completed")  # will get task.yaml too, see below
        # A dir with no task.yaml at all must be skipped entirely, not crash the sweep.
        os.makedirs(os.path.join(root, "task-5-no-yaml", "workspace", "node_modules"))

        report = m.run(root, dry_run=False)
        touched_ids = {e["task_id"] for e in report["touched"]}
        assert touched_ids == {"task-1-completed", "task-3-failed", "task-4-no-yaml-dir-only"}
        assert not os.path.isdir(os.path.join(root, "task-1-completed", "workspace", "node_modules"))
        assert os.path.isdir(os.path.join(root, "task-2-blocked", "workspace", "node_modules"))
        assert report["reclaimed_bytes"] == 1024 * 3


def test_status_passed_explicitly_overrides_task_yaml_read():
    """The library call shape used by veridian-task.py's checkpoint hook
    passes the just-written status directly (no need to re-read the file
    it just wrote under its own lock)."""
    m = _load_module()
    with tempfile.TemporaryDirectory() as root:
        task_dir = _make_task(root, "task-explicit", "blocked")  # on-disk says blocked
        entry = m.prune_one(task_dir, status="completed")  # caller asserts it's now terminal
        assert entry["action"] == "deleted"


def test_cli_json_output_is_well_formed():
    m = _load_module()
    with tempfile.TemporaryDirectory() as root:
        _make_task(root, "task-cli", "completed")
        out = subprocess.run(
            [sys.executable, os.path.join(SCRIPTS_DIR, "prune_task_node_modules.py"),
             "--dry-run", "--tasks-root", root],
            capture_output=True, text=True, timeout=60)
        assert out.returncode == 0
        parsed = json.loads(out.stdout)
        assert parsed["mode"] == "dry-run"
        assert parsed["reclaimed_bytes"] == 1024


if __name__ == "__main__":
    import pytest
    sys.exit(pytest.main([__file__, "-v"]))
