#!/usr/bin/env python3
"""Real integration test: veridian-task.py's `checkpoint --status` command
must self-prune a task's own workspace/node_modules the instant that
checkpoint call lands a terminal status (the real recurrence fix for
UMR-20260806-082230-54b8 / parent UMR-20260806-071025-1d28 -- see
prune_task_node_modules.py's own docstring for the root-cause writeup).

Drives the real cmd_checkpoint() function against a real, fully-formed
task.yaml in an isolated scratch dir (never the real production
/opt/veridian/ai-os/tasks tree) -- same isolation convention
test_ocid063_handoff_envelope.py already documents and uses (monkeypatch
AI_OS/CONTROLLER/CONTROLLER_LOCK to a scratch dir; the workspace itself is
a plain directory, not a real git repo -- cmd_checkpoint's own git calls
are wrapped in `except subprocess.CalledProcessError: pass`, so a
non-git workspace is a real, already-supported no-op path, not a test
hack). _sync_to_app/_auto_log_task_event are stubbed to no-ops so this
test never makes a real network call or writes to the real production
log index.
"""
import importlib.util
import os
import sys
import tempfile

import pytest

SCRIPTS_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, SCRIPTS_DIR)


def load_veridian_task():
    spec = importlib.util.spec_from_file_location(
        "veridian_task_checkpoint_prune_test", os.path.join(SCRIPTS_DIR, "veridian-task.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


@pytest.fixture
def isolated_vt():
    """Real veridian-task.py module with AI_OS/CONTROLLER/CONTROLLER_LOCK
    redirected into a fresh scratch dir, and the two real-world-facing
    side-effect functions stubbed to no-ops. Yields (vt, scratch_dir)."""
    vt = load_veridian_task()
    scratch_dir = tempfile.mkdtemp(prefix="checkpoint-prune-test-")
    vt.AI_OS = scratch_dir
    vt.CONTROLLER = os.path.join(scratch_dir, "CONTROLLER.yaml")
    vt.CONTROLLER_LOCK = os.path.join(scratch_dir, ".controller.lock")
    with open(vt.CONTROLLER, "w") as f:
        f.write("server: VERIDIAN-DEV-TEST\ntasks: []\n")
    vt._sync_to_app = lambda *a, **kw: None
    vt._auto_log_task_event = lambda *a, **kw: None
    try:
        yield vt, scratch_dir
    finally:
        import shutil
        shutil.rmtree(scratch_dir, ignore_errors=True)


def _make_real_task(vt, scratch_dir, task_id, status, with_node_modules=True):
    task_dir = os.path.join(scratch_dir, "tasks", task_id)
    workspace = os.path.join(task_dir, "workspace")
    os.makedirs(workspace)
    if with_node_modules:
        nm = os.path.join(workspace, "node_modules", "some-pkg")
        os.makedirs(nm)
        with open(os.path.join(nm, "index.js"), "wb") as f:
            f.write(b"x" * 2048)
    # cmd_checkpoint's real state-machine guard (see its own inline
    # comment): a checkpoint can only land status="completed" if this
    # task's own checkpoint history already contains a prior
    # status="pending_review" entry. Seed that real prior checkpoint here
    # so the completed-status test below exercises the actual reachable
    # path, not a shortcut around that guard.
    checkpoints = [{"at": vt.now(), "status": "pending_review",
                    "files_modified": [], "completed_steps": [],
                    "remaining_steps": [], "recent_commits": [], "note": "seed"}] \
        if status == "pending_review" else []
    task = {
        "id": task_id, "title": "real test task", "status": status,
        "repo": "compliance-tracker", "branch": f"worker/{task_id}",
        "workspace": workspace, "task_dir": task_dir,
        "service": f"veridian-worker@{task_id}.service",
        "created_at": vt.now(), "last_checkpoint_at": None,
        "completed_steps": [], "remaining_steps": [], "files_modified": [],
        "checkpoints": checkpoints, "execution_seconds": 0, "restart_count": 0,
        "token_usage": None, "hold_for_owner_signoff": False,
    }
    vt.save_task(task_id, task)
    return task_dir


def _checkpoint_args(task_id, status):
    import argparse
    return argparse.Namespace(
        task_id=task_id, status=status, note="real test checkpoint",
        auto=False, handoff_envelope=None, evidence_json=None,
    )


def test_checkpoint_to_completed_prunes_node_modules(isolated_vt):
    vt, scratch_dir = isolated_vt
    task_id = "task-real-completed"
    task_dir = _make_real_task(vt, scratch_dir, task_id, status="pending_review")

    vt.cmd_checkpoint(_checkpoint_args(task_id, "completed"))

    nm_path = os.path.join(task_dir, "workspace", "node_modules")
    assert not os.path.isdir(nm_path), "node_modules must be pruned once status lands on 'completed'"
    assert os.path.isfile(os.path.join(task_dir, "task.yaml")), "task.yaml itself must never be touched"
    reloaded = vt.load_task(task_id)
    assert reloaded["status"] == "completed"


def test_checkpoint_to_blocked_does_not_prune_node_modules(isolated_vt):
    vt, scratch_dir = isolated_vt
    task_id = "task-real-blocked"
    task_dir = _make_real_task(vt, scratch_dir, task_id, status="in_progress")

    vt.cmd_checkpoint(_checkpoint_args(task_id, "blocked"))

    nm_path = os.path.join(task_dir, "workspace", "node_modules")
    assert os.path.isdir(nm_path), "node_modules must survive a non-terminal status transition"


def test_checkpoint_to_failed_prunes_node_modules(isolated_vt):
    vt, scratch_dir = isolated_vt
    task_id = "task-real-failed"
    task_dir = _make_real_task(vt, scratch_dir, task_id, status="in_progress")

    vt.cmd_checkpoint(_checkpoint_args(task_id, "failed"))

    nm_path = os.path.join(task_dir, "workspace", "node_modules")
    assert not os.path.isdir(nm_path)


if __name__ == "__main__":
    sys.exit(pytest.main([__file__, "-v"]))
